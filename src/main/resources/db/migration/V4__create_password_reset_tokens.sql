-- Tokens de recuperação de senha (guardamos apenas o hash SHA-256 do token)
CREATE TABLE PASSWORD_RESET_TOKENS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    VETERINARIO_ID NUMBER NOT NULL,
    TOKEN_HASH VARCHAR2(64) NOT NULL UNIQUE,
    EXPIRA_EM TIMESTAMP NOT NULL,
    USADO NUMBER(1) DEFAULT 0 NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT FK_PRT_VETERINARIO FOREIGN KEY (VETERINARIO_ID)
        REFERENCES VETERINARIOS(ID) ON DELETE CASCADE
);
